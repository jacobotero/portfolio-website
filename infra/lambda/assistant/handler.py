_api_key_cache = None


class GeminiError(Exception):
    """Raised when the Gemini call fails or returns something unusable."""


def handler(event, _context):
    try:
        body = json.loads(event.get("body") or "{}")
    except json.JSONDecodeError:
        return _response(400, {"error": "invalid JSON body"})

    messages = body.get("messages")
    validation_error = _validate_messages(messages)
    if validation_error:
        return _response(400, {"error": validation_error})

    try:
        answer = _ask_gemini(messages)
    except GeminiError:
        return _response(
            503, {"error": "the assistant is busy right now, try again shortly"}
        )

    return _response(200, {"answer": answer})


def _validate_messages(messages) -> str | None:
    if not isinstance(messages, list) or not messages:
        return "messages is required and must be a non-empty list"
    if len(messages) > MAX_MESSAGES:
        return "too many messages"
    for msg in messages:
        if not isinstance(msg, dict):
            return "each message must be an object"
        if msg.get("role") not in ALLOWED_ROLES:
            return "invalid message role"
        text = (msg.get("text") or "").strip()
        if not text:
            return "message text is required"
        if len(text) > MAX_MESSAGE_LENGTH:
            return "message too long"
    if messages[-1]["role"] != "user":
        return "the last message must be from the user"
    return None


def _get_api_key() -> str:
    # Fetched once per warm Lambda instance rather than read from an
    # environment variable, so the key is never a static value baked into
    # the function's config — only this execution role, scoped to exactly
    # this one parameter, can retrieve it.
    global _api_key_cache
    if _api_key_cache is None:
        _api_key_cache = ssm.get_parameter(Name=API_KEY_PARAM, WithDecryption=True)[
            "Parameter"
        ]["Value"]
    return _api_key_cache


def _ask_gemini(messages: list) -> str:
    # Gemini's own role vocabulary is "user" / "model", not "user" / "assistant".
    contents = [
        {
            "role": "model" if msg["role"] == "assistant" else "user",
            "parts": [{"text": msg["text"].strip()}],
        }
        for msg in messages
    ]
    payload = {
        "systemInstruction": {"parts": [{"text": SYSTEM_PROMPT}]},
        "contents": contents,
        "generationConfig": {"maxOutputTokens": 300, "temperature": 0.4},
    }
    request = urllib.request.Request(
        GEMINI_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Content-Type": "application/json",
            "x-goog-api-key": _get_api_key(),
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=15) as res:
            data = json.loads(res.read().decode("utf-8"))
    except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError) as exc:
        raise GeminiError(str(exc)) from exc

    try:
        return data["candidates"][0]["content"]["parts"][0]["text"].strip()
    except (KeyError, IndexError, TypeError) as exc:
        raise GeminiError("unexpected response shape") from exc


def _response(status: int, payload: dict):
    return {
        "statusCode": status,
        "headers": {"Content-Type": "application/json"},
        "body": json.dumps(payload),
    }
